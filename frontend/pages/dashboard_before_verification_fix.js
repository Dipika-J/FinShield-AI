const API="http://127.0.0.1:8000/api/transactions/analyze";

let currentTransaction=null;
let currentResult=null;
let currentTransactionId=null;
let liveTimer=null;

function normalTransaction(){
    const locations=["Chennai","Coimbatore","Madurai","Trichy","Pune"];
    const methods=["UPI","Credit Card","Debit Card","Net Banking"];

    return {
        amount:Math.floor(Math.random()*9000)+2000,
        hour:Math.floor(Math.random()*10)+9,
        frequency:Math.floor(Math.random()*4)+1,
        failed_attempts:0,
        location:locations[Math.floor(Math.random()*locations.length)],
        device:Math.random()<0.8 ? "Known" : "New",
        payment_method:methods[Math.floor(Math.random()*methods.length)]
    };
}

function fraudTransaction(){
    const locations=[
        "Mumbai",
        "Bengaluru",
        "Hyderabad",
        "Delhi",
        "Kolkata",
        "Pune"
    ];

    const methods=[
        "UPI",
        "Credit Card",
        "Debit Card",
        "Net Banking",
        "Wallet"
    ];

    const devices=["New","Unknown","New","Known"];

    return {
        amount:Math.floor(Math.random()*120000)+35000,
        hour:Math.floor(Math.random()*6),
        frequency:Math.floor(Math.random()*10)+7,
        failed_attempts:Math.floor(Math.random()*4)+2,
        location:locations[Math.floor(Math.random()*locations.length)],
        device:devices[Math.floor(Math.random()*devices.length)],
        payment_method:methods[Math.floor(Math.random()*methods.length)]
    };
}

function displayStatus(result){

    if(result.risk_level==="CRITICAL"){
        return "AWAITING VERIFICATION";
    }

    if(result.risk_level==="HIGH"){
        return "HOLD • VERIFICATION REQUIRED";
    }

    if(result.risk_level==="MEDIUM"){
        return "REVIEW REQUIRED";
    }

    return "APPROVED";
}

function setText(id,value){
    const element=document.getElementById(id);

    if(element){
        element.textContent=value;
    }
}

async function analyze(transaction){

    currentTransaction=transaction;

    setText("riskScore","...");
    setText("riskLevel","ANALYSING");
    setText("fraudProbability","...");
    setText("recommendation","ANALYSING");

    addTimeline(
        "Transaction received",
        "Pre-authorization analysis initiated"
    );

    try{

        const response=await fetch(API,{
            method:"POST",
            headers:{
                "Content-Type":"application/json"
            },
            body:JSON.stringify(transaction)
        });

        const data=await response.json();

        if(!response.ok){
            throw new Error(data.detail || "Analysis failed");
        }

        currentResult=data.analysis;

        /*
        IMPORTANT:
        Use the transaction ID generated by the backend.
        */
        currentTransactionId=data.transaction_id;

        updateAI(currentResult);
        updateBehaviour(transaction);

        addTransaction(
            transaction,
            currentResult,
            currentTransactionId
        );

        addTimeline(
            "AI risk analysis completed",
            "Random Forest model generated risk assessment"
        );

        addTimeline(
            "Pre-authorization decision",
            displayStatus(currentResult)
        );

        if(currentResult.risk_score>=60){

            showAlert(
                "Risk detected: " +
                currentResult.risk_level +
                " — " +
                displayStatus(currentResult)
            );
        }

        openInvestigation(
            currentTransactionId,
            transaction,
            currentResult
        );

    }catch(error){

        console.error(error);

        setText("riskLevel","ERROR");
        setText("recommendation","ANALYSIS FAILED");

        addTimeline(
            "AI analysis error",
            error.message || "Unable to connect to FinShield backend"
        );

        showAlert("AI backend connection failed.");
    }
}

function updateAI(result){

    setText("riskScore",result.risk_score);
    setText("riskLevel",result.risk_level);

    setText(
        "fraudProbability",
        result.fraud_probability+"%"
    );

    setText(
        "recommendation",
        displayStatus(result)
    );

    const box=document.getElementById("factors");

    if(!box){
        return;
    }

    box.innerHTML="";

    const factors=result.risk_factors || [];

    if(factors.length===0){

        const item=document.createElement("div");

        item.className="factor";
        item.textContent="No major risk indicators detected.";

        box.appendChild(item);

    }else{

        factors.forEach(function(factor){

            const item=document.createElement("div");

            item.className="factor";
            item.textContent=factor;

            box.appendChild(item);
        });
    }
}

function updateBehaviour(transaction){

    setText(
        "currentAmount",
        "Rs. "+Number(transaction.amount).toLocaleString("en-IN")
    );

    setText(
        "currentDevice",
        transaction.device
    );

    setText(
        "currentFrequency",
        transaction.frequency
    );
}

function addTransaction(transaction,result,id){

    const list=document.getElementById("transactionList");

    if(!list){
        return;
    }

    const item=document.createElement("div");

    item.className="transaction";

    let className="low";

    if(result.risk_level==="CRITICAL"){
        className="critical";
    }
    else if(result.risk_level==="HIGH"){
        className="high";
    }
    else if(result.risk_level==="MEDIUM"){
        className="medium";
    }

    item.innerHTML=`

        <div class="txleft">

            <div class="txicon">
                TX
            </div>

            <div>

                <div class="txid">
                    ${id}
                </div>

                <div class="meta">
                    ${transaction.location}
                    •
                    ${transaction.payment_method}
                    •
                    ${transaction.device} Device
                </div>

            </div>

        </div>

        <div class="txright">

            <div class="amount">
                Rs. ${Number(transaction.amount).toLocaleString("en-IN")}
            </div>

            <div class="pill ${className}">
                ${result.risk_level}
            </div>

            <div class="meta">
                ${displayStatus(result)}
            </div>

        </div>
    `;

    item.onclick=function(){

        openInvestigation(
            id,
            transaction,
            result
        );

    };

    list.prepend(item);
}

function openInvestigation(id,transaction,result){

    currentTransactionId=id;
    currentTransaction=transaction;
    currentResult=result;

    setText("investId",id);

    setText(
        "investMeta",
        transaction.location+
        " • "+
        transaction.payment_method+
        " • "+
        transaction.device+
        " Device"
    );

    setText(
        "investScore",
        result.risk_score+"/100"
    );

    setText(
        "investLevel",
        result.risk_level
    );

    setText(
        "investAmount",
        "Rs. "+
        Number(transaction.amount).toLocaleString("en-IN")
    );

    setText(
        "investLocation",
        transaction.location
    );

    setText(
        "investDevice",
        transaction.device
    );

    setText(
        "investPayment",
        transaction.payment_method
    );

    setText(
        "investFrequency",
        transaction.frequency
    );

    setText(
        "investFailed",
        transaction.failed_attempts
    );

    setText(
        "investProbability",
        result.fraud_probability+"%"
    );

    const factors=document.getElementById("investFactors");

    if(factors){

        factors.innerHTML="";

        (result.risk_factors || []).forEach(function(factor){

            const item=document.createElement("div");

            item.className="factor";
            item.textContent=factor;

            factors.appendChild(item);
        });
    }

    const drawer=document.getElementById("drawer");
    const overlay=document.getElementById("overlay");

    if(drawer){
        drawer.classList.add("open");
    }

    if(overlay){
        overlay.style.display="block";
    }
}

function closeInvestigation(){

    const drawer=document.getElementById("drawer");
    const overlay=document.getElementById("overlay");

    if(drawer){
        drawer.classList.remove("open");
    }

    if(overlay){
        overlay.style.display="none";
    }
}

function addTimeline(title,text){

    const timeline=document.getElementById("timeline");

    if(!timeline){
        return;
    }

    const event=document.createElement("div");

    event.className="event";

    event.innerHTML=`

        <div class="event-dot"></div>

        <div>

            <strong>${title}</strong>

            <span>${text}</span>

        </div>
    `;

    timeline.prepend(event);
}

function showAlert(message){

    const box=document.getElementById("alertBox");
    const text=document.getElementById("alertText");

    if(!box || !text){
        return;
    }

    text.textContent=message;

    box.classList.add("show");

    setTimeout(function(){

        box.classList.remove("show");

    },4500);
}

function simulateFraud(){

    analyze(
        fraudTransaction()
    );
}

function simulateNormal(){

    analyze(
        normalTransaction()
    );
}

/* CUSTOMER VERIFICATION */

function goCustomerVerification(){

    if(!currentTransactionId){

        showAlert(
            "No transaction selected for customer verification."
        );

        return;
    }

    window.location.href=
        "customer.html?transaction_id="+
        encodeURIComponent(currentTransactionId);
}

/* EMPLOYEE DECISION */

async function decision(action){

    if(!currentTransactionId){

        showAlert(
            "No transaction is currently selected."
        );

        return;
    }

    if(action==="VERIFY"){

        goCustomerVerification();
        return;
    }

    try{

        const response=await fetch(
            "http://127.0.0.1:8000/api/transactions/decision",
            {
                method:"POST",

                headers:{
                    "Content-Type":"application/json"
                },

                body:JSON.stringify({
                    transaction_id:currentTransactionId,
                    decision:action
                })
            }
        );

        const data=await response.json();

        if(!response.ok){

            throw new Error(
                data.detail || "Decision failed"
            );
        }

        addTimeline(
            "Employee decision: "+action,
            data.status
        );

        showAlert(
            "Transaction "+data.status
        );

        closeInvestigation();

    }catch(error){

        showAlert(
            "Decision failed: "+error.message
        );
    }
}

/* LIVE MODE */

function startLive(){

    if(liveTimer){
        return;
    }

    const startButton=
        document.querySelector(".btn-live");

    const stopButton=
        document.getElementById("stopLiveBtn");

    if(startButton){
        startButton.disabled=true;
    }

    if(stopButton){
        stopButton.style.display="inline-block";
    }

    showAlert(
        "Live transaction monitoring started."
    );

    analyze(
        Math.random()<0.4
        ? fraudTransaction()
        : normalTransaction()
    );

    liveTimer=setInterval(function(){

        analyze(
            Math.random()<0.4
            ? fraudTransaction()
            : normalTransaction()
        );

    },7000);
}

function stopLive(){

    if(liveTimer){

        clearInterval(liveTimer);

        liveTimer=null;
    }

    const startButton=
        document.querySelector(".btn-live");

    const stopButton=
        document.getElementById("stopLiveBtn");

    if(startButton){
        startButton.disabled=false;
    }

    if(stopButton){
        stopButton.style.display="none";
    }

    showAlert(
        "Live transaction monitoring stopped."
    );

    addTimeline(
        "Live monitoring stopped",
        "Automatic transaction simulation is paused"
    );
}

/* CREATE SEPARATE STOP BUTTON */

function setupLiveButtons(){

    const startButton=
        document.querySelector(".btn-live");

    if(
        !startButton ||
        document.getElementById("stopLiveBtn")
    ){
        return;
    }

    const stopButton=document.createElement("button");

    stopButton.id="stopLiveBtn";
    stopButton.className="btn btn-live";
    stopButton.textContent="STOP LIVE MODE";

    stopButton.onclick=stopLive;

    stopButton.style.display="none";

    startButton.insertAdjacentElement(
        "afterend",
        stopButton
    );
}

/* CUSTOMER VERIFICATION BUTTON */

function setupCustomerButton(){

    const actionGrid=
        document.querySelector(".drawer .action-grid");

    if(
        !actionGrid ||
        document.getElementById("customerVerifyBtn")
    ){
        return;
    }

    const button=document.createElement("button");

    button.id="customerVerifyBtn";
    button.className="action";
    button.textContent="CUSTOMER VERIFICATION";

    button.onclick=
        goCustomerVerification;

    actionGrid.parentElement.appendChild(
        button
    );
}

document.addEventListener(
    "DOMContentLoaded",
    function(){

        setupLiveButtons();
        setupCustomerButton();

    }
);
